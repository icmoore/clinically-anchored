"""Follow-up extensions: the patient asks, a clinician accepts or declines (migration 16).

After the nine-window care period ends by schedule the patient may ask for more follow-up
(core/extension.py has the rules). Accepting creates a NEW episode that continues the old one;
declining is final for that care period. The request reason and the decision are thread entries of
their own kinds (not ordinary messages), so summaries and briefs see them and a decision never
grants a reply.

Audit comes FIRST here: `extension.requested` / `extension.accepted` / `extension.declined` are
written under ids generated by the api, then the database function saves the rows under the same
ids. If the save then loses a race (it is the database that has the last word) the audit log has
one event with no row: reconcile lists that as informational "dangling", never as a gap.

Only owner and clinician can decide, like a discharge."""

import logging
import uuid

from fastapi import APIRouter, Depends, HTTPException

from clinically_anchored_api.api.episodes import audit_or_500, iso, request_outs
from clinically_anchored_api.core import episodes
from clinically_anchored_api.core.audit import AuditWriteError, record_event
from clinically_anchored_api.core.auth import ClinicMember, require_clinic_member
from clinically_anchored_api.core.db import get_supabase
from clinically_anchored_api.core.extension import (
    REASON_MAX,
    Standing,
    decision_entry_body,
)
from clinically_anchored_api.core.security import PatientContext, require_patient_ended_mode
from clinically_anchored_api.schemas import (
    ExtensionDecision,
    ExtensionRequestCreate,
    ExtensionRequestOut,
    PatientExtensionOut,
)

logger = logging.getLogger(__name__)

router = APIRouter(tags=["extensions"])

DECIDE_ROLES = frozenset({"owner", "clinician"})

# The database's error codes (migration 16) -> what the caller is told.
_REQUEST_ERRORS = (
    ("extension_reason_invalid", 422, "Please write a short reason (up to %d characters)."),
    ("extension_term_running", 409, "Your follow-up through this app has not ended yet."),
    ("extension_not_eligible", 409, "More follow-up can't be requested for this care period."),
    ("extension_already_requested", 409, "You have already sent a request."),
    ("extension_window_over", 410, "The time to request more follow-up has passed."),
    ("episode_not_found", 410, "This care period has ended."),
    ("extension_bad_schedule", 503, "Follow-up requests are not available right now."),
)
_DECIDE_ERRORS = (
    ("extension_not_found", 404, "Request not found."),
    ("extension_not_pending", 409, "This request has already been decided."),
    (
        "extension_superseded", 409,
        "This patient has a newer care period, so this cannot be accepted.",
    ),
    ("extension_message_invalid", 422, "The message is empty or too long."),
)


def _raise_for(exc: Exception, table) -> None:
    text = str(exc)
    for code, status, detail in table:
        if code in text:
            raise HTTPException(
                status_code=status, detail=detail.replace("%d", str(REASON_MAX))
            ) from exc


# --- patient side ----------------------------------------------------------------------------


def patient_extension(supabase, ctx: PatientContext) -> PatientExtensionOut | None:
    """The follow-up block of the patient's state, or None when there is nothing to show."""
    episode = ctx.episode
    number = 0
    if episode.get("kind") == "extension":
        number = len(episodes.chain(supabase, episode)) - 1
    ext = ctx.extension
    if ext.standing in (Standing.ELIGIBLE, Standing.PENDING, Standing.DECLINED):
        request = ctx.request
        return PatientExtensionOut(
            standing=ext.standing.value,
            request_by=iso(ext.request_by),
            reason_max=REASON_MAX,
            requested_at=str(request["requested_at"]) if request else None,
            decision_message=request["decision_message"] if request else None,
            extension_no=number,
        )
    if episode.get("kind") == "extension" and not ctx.state.closed:
        # Inside a running extension: show the clinician's words from the acceptance.
        accepted = episodes.request_for(supabase, episode["extends_episode_id"])
        return PatientExtensionOut(
            standing="accepted",
            reason_max=REASON_MAX,
            requested_at=str(accepted["requested_at"]) if accepted else None,
            decision_message=accepted["decision_message"] if accepted else None,
            extension_no=number,
        )
    return None


@router.post("/extension-request", response_model=PatientExtensionOut)
def patient_request_extension(
    body: ExtensionRequestCreate, ctx: PatientContext = Depends(require_patient_ended_mode)
) -> PatientExtensionOut:
    """The patient asks for more follow-up. Only when their care period ended by schedule, they
    have not asked before, and the time to ask has not run out."""
    supabase = get_supabase()
    ext = ctx.extension
    if ctx.request is not None:
        raise HTTPException(status_code=409, detail="You have already sent a request.")
    if not ext.can_request:
        raise HTTPException(
            status_code=410, detail="The time to request more follow-up has passed."
        )
    schedule = episodes.default_extension_schedule(supabase)
    if schedule is None:
        raise HTTPException(
            status_code=503, detail="Follow-up requests are not available right now."
        )

    request_id, message_id = str(uuid.uuid4()), str(uuid.uuid4())
    try:
        record_event(
            supabase,
            clinic_id=ctx.clinic_id,
            event_type="extension.requested",
            payload={
                "request_id": request_id,
                "episode_id": ctx.episode_id,
                "patient_id": ctx.patient_id,
                "message_id": message_id,
                "schedule_version": schedule.version,
                "request_by": iso(ext.request_by),
                "reason": body.reason,
            },
            metadata={
                "ref_type": "extension_request",
                "ref_id": request_id,
                "patient_id": ctx.patient_id,
                "episode_id": ctx.episode_id,
                "schedule_version": schedule.version,
                "actor": {"type": "patient", "id": ctx.patient_id},
            },
        )
    except AuditWriteError as exc:
        logger.error("extension request not audited, nothing saved: %s", exc)
        raise HTTPException(status_code=500, detail="Your request could not be saved.") from exc

    try:
        out = (
            supabase.rpc(
                "request_extension",
                {
                    "p_clinic_id": ctx.clinic_id,
                    "p_episode_id": ctx.episode_id,
                    "p_request_id": request_id,
                    "p_message_id": message_id,
                    "p_reason": body.reason,
                    "p_schedule_version": schedule.version,
                    "p_expires_at": iso(ext.request_by),
                },
            )
            .execute()
            .data
        )
    except Exception as exc:
        _raise_for(exc, _REQUEST_ERRORS)
        raise
    request = out["request"]
    return PatientExtensionOut(
        standing="pending",
        request_by=iso(ext.request_by),
        reason_max=REASON_MAX,
        requested_at=str(request["requested_at"]),
    )


# --- clinician side ---------------------------------------------------------------------------


def _load_pending(supabase, clinic_id: str, request_id: str, member: ClinicMember) -> dict:
    if member.role not in DECIDE_ROLES:
        raise HTTPException(
            status_code=403, detail="Only a clinician can accept or decline a request."
        )
    rows = (
        supabase.table("extension_requests").select(episodes.REQUEST_COLUMNS)
        .eq("id", request_id).eq("clinic_id", clinic_id).execute().data
    )
    if not rows:
        raise HTTPException(status_code=404, detail="Request not found.")
    if rows[0]["status"] != "pending":
        raise HTTPException(status_code=409, detail="This request has already been decided.")
    return rows[0]


def _decide(
    supabase, clinic_id: str, request_id: str, decision: str, body: ExtensionDecision,
    member: ClinicMember,
) -> ExtensionRequestOut:
    request = _load_pending(supabase, clinic_id, request_id, member)
    accepted = decision == "accepted"
    latest = episodes.latest_episode(supabase, clinic_id, request["patient_id"])
    if accepted and latest is not None and latest["id"] != request["episode_id"]:
        raise HTTPException(
            status_code=409,
            detail="This patient has a newer care period, so this cannot be accepted.",
        )

    entry_id, new_episode_id = str(uuid.uuid4()), str(uuid.uuid4())
    entry_body = decision_entry_body(decision, body.message)
    try:
        record_event(
            supabase,
            clinic_id=clinic_id,
            event_type=f"extension.{'accepted' if accepted else 'declined'}",
            payload={
                "request_id": request["id"],
                "episode_id": request["episode_id"],
                "patient_id": request["patient_id"],
                "entry_id": entry_id,
                "extension_episode_id": new_episode_id if accepted else None,
                "schedule_version": request["schedule_version"] if accepted else None,
                "message": body.message,
                "decided_by": member.user_id,
            },
            metadata={
                "ref_type": "extension_request",
                "ref_id": request["id"],
                "patient_id": request["patient_id"],
                "episode_id": request["episode_id"],
                "actor": episodes.member_actor(member),
            },
        )
    except AuditWriteError as exc:
        logger.error("extension decision not audited, nothing saved: %s", exc)
        raise HTTPException(
            status_code=500, detail="Not saved: the decision could not be audited."
        ) from exc

    try:
        out = (
            supabase.rpc(
                "decide_extension",
                {
                    "p_clinic_id": clinic_id,
                    "p_request_id": request["id"],
                    "p_decision": decision,
                    "p_decided_by": member.user_id,
                    "p_message": body.message,
                    "p_entry_id": entry_id,
                    "p_entry_body": entry_body,
                    "p_episode_id": new_episode_id,
                },
            )
            .execute()
            .data
        )
    except Exception as exc:
        _raise_for(exc, _DECIDE_ERRORS)
        raise
    if accepted:
        child = out["episode"]
        audit_or_500(
            supabase, "episode.created", child, member,
            {
                "extends_episode_id": request["episode_id"],
                "extension_request_id": request["id"],
                "started_at": child["started_at"],
                "surgery_date": str(child["surgery_date"]),
                "created_by": member.user_id,
            },
        )
    return request_outs(supabase, [out["request"]])[request["id"]]


@router.post(
    "/clinics/{clinic_id}/extension-requests/{request_id}/accept",
    response_model=ExtensionRequestOut,
)
def accept_request(
    clinic_id: str,
    request_id: str,
    body: ExtensionDecision | None = None,
    member: ClinicMember = Depends(require_clinic_member),
) -> ExtensionRequestOut:
    """Accept: a new extension episode starts now (its first window opens at this moment)."""
    return _decide(
        get_supabase(), clinic_id, request_id, "accepted", body or ExtensionDecision(), member
    )


@router.post(
    "/clinics/{clinic_id}/extension-requests/{request_id}/decline",
    response_model=ExtensionRequestOut,
)
def decline_request(
    clinic_id: str,
    request_id: str,
    body: ExtensionDecision | None = None,
    member: ClinicMember = Depends(require_clinic_member),
) -> ExtensionRequestOut:
    """Decline: final for this care period. The patient is shown the message, if any."""
    return _decide(
        get_supabase(), clinic_id, request_id, "declined", body or ExtensionDecision(), member
    )

